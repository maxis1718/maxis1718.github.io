#!/usr/bin/env python3
"""Bake the Cubic 11 (俐方體11號, OFL) pixel font into src/font.js.

Usage (from repo root or anywhere):
    python3 tools/cjk.py            # scan src/*.js + tools/extra-chars.txt, write src/font.js + OFL.txt
    CUBIC_TTF=/path/Cubic_11.ttf python3 tools/cjk.py

Character set = printable ASCII 0x20-0x7E
              + every non-ASCII char found in src/*.js (except font.js)
              + every char in tools/extra-chars.txt (if present).
The TTF is downloaded from GitHub (ACh-K/Cubic-11) into /tmp/art/font/ if not found.
At 12 px the font is exactly 1 font px per pixel (UPM 1200 -> 100 units/px); glyphs are
binarised with a threshold (no anti-aliasing) and stored as packed 1-bit bitmaps.

font.js format:  export const GLYPHS = { "<ch>": "adv,xo,yo,w,h,<base64 row-major bits>" , ...}
  adv = advance width, (xo, yo) = bitmap offset from pen position / top of 14px em box
  (ascent 10: CJK occupies rows 1..11, latin descenders reach row 13).
"""
import base64
import glob
import json
import os
import sys
import urllib.request

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
OUT = os.path.join(SRC, "font.js")
EXTRA = os.path.join(ROOT, "tools", "extra-chars.txt")
RAW = "https://raw.githubusercontent.com/ACh-K/Cubic-11/main/"
CACHE = os.environ.get("CUBIC_CACHE", "/tmp/art/font")
SIZE = 12
THRESH = 128


def fetch(name):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, os.path.basename(name))
    if not os.path.exists(path):
        print("downloading", RAW + name, file=sys.stderr)
        urllib.request.urlretrieve(RAW + name, path)
    return path


def collect_chars():
    chars = set(chr(c) for c in range(0x20, 0x7F))
    for fn in sorted(glob.glob(os.path.join(SRC, "*.js"))):
        if os.path.basename(fn) == "font.js":
            continue
        with open(fn, encoding="utf-8") as f:
            for ch in f.read():
                if ord(ch) > 0x7E and not ch.isspace() and ch.isprintable():
                    chars.add(ch)
    if os.path.exists(EXTRA):
        with open(EXTRA, encoding="utf-8") as f:
            for ch in f.read():
                if not ch.isspace() and ch.isprintable():
                    chars.add(ch)
    return sorted(chars)


def main():
    ttf = os.environ.get("CUBIC_TTF") or fetch("fonts/ttf/Cubic_11.ttf")
    font = ImageFont.truetype(ttf, SIZE)
    try:
        from fontTools.ttLib import TTFont

        cmap = TTFont(ttf).getBestCmap()
    except Exception:  # fontTools optional
        cmap = None

    glyphs, missing = {}, []
    for ch in collect_chars():
        if cmap is not None and ord(ch) not in cmap:
            missing.append(ch)
            continue
        adv = int(round(font.getlength(ch)))
        pad = 4
        im = Image.new("L", (adv + pad * 2 + 8, 20), 0)
        ImageDraw.Draw(im).text((pad, 0), ch, font=font, fill=255)
        px = im.load()
        on = [(x, y) for y in range(im.height) for x in range(im.width) if px[x, y] >= THRESH]
        if not on:
            glyphs[ch] = "%d,0,0,0,0," % adv
            continue
        x0 = min(p[0] for p in on); x1 = max(p[0] for p in on)
        y0 = min(p[1] for p in on); y1 = max(p[1] for p in on)
        w, h = x1 - x0 + 1, y1 - y0 + 1
        bits = bytearray((w * h + 7) // 8)
        for (x, y) in on:
            i = (y - y0) * w + (x - x0)
            bits[i >> 3] |= 0x80 >> (i & 7)
        glyphs[ch] = "%d,%d,%d,%d,%d,%s" % (adv, x0 - pad, y0, w, h, base64.b64encode(bytes(bits)).decode())

    body = ",\n".join("%s:%s" % (json.dumps(k, ensure_ascii=False), json.dumps(v)) for k, v in glyphs.items())
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// GENERATED by tools/cjk.py from Cubic 11 (俐方體11號, SIL OFL 1.1, see OFL.txt). Do not edit.\n")
        f.write("// value = 'adv,xo,yo,w,h,base64(1-bit rows)'; em box 14px, ascent 10.\n")
        f.write("export const GLYPHS = {\n" + body + "\n};\n")
    # licence
    try:
        lic = fetch("OFL.txt")
        with open(lic, encoding="utf-8") as src, open(os.path.join(ROOT, "OFL.txt"), "w", encoding="utf-8") as dst:
            dst.write("Bitmap glyphs in src/font.js are derived from Cubic 11 (俐方體11號)\n"
                      "https://github.com/ACh-K/Cubic-11 - licensed under the SIL Open Font License 1.1:\n\n")
            dst.write(src.read())
    except Exception as e:  # keep going offline
        print("warning: could not fetch OFL.txt:", e, file=sys.stderr)
    print("baked %d glyphs -> %s (%d bytes)" % (len(glyphs), OUT, os.path.getsize(OUT)))
    if missing:
        print("missing in font (skipped): " + "".join(missing), file=sys.stderr)


if __name__ == "__main__":
    main()
